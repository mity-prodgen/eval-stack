#!/usr/bin/env python3
"""Noise baseline for post 1: how often does a verdict change between runs with no attack at all?

Reads the original run (judgments.jsonl, repeat 0) and the C0-only re-runs (judgments_repeat1.jsonl,
judgments_repeat2.jsonl, made with `run.py --condition C0 --repeat K --live`). Per judge x arm:

  changed       share of items (all 120, both classes) whose pass/fail verdict differs between two runs,
                averaged over the 3 run pairs (0-1, 0-2, 1-2), CI = bootstrap over items.
  any change    share of items whose verdict is not the same in all 3 runs.
  noise flip    the post-1 flip-rate definition with C0 re-run as the "attack": of wrong answers that
                FAIL in the original C0 run, the share that PASS in a re-run (pooled over re-runs 1, 2).
                This is the number to hold next to post 1's flip rates.

An item counts only if its verdict is valid in every run being compared. Writes persuasion/NOISE.md
and persuasion/results/noise_metrics.json.

    python persuasion/noise.py                # re-runs 1 and 2
    python persuasion/noise.py --repeats 1    # interim, one re-run (only the 0-1 pair)
"""

from __future__ import annotations

import argparse
import json
from itertools import combinations

from analyze import N_BOOT, pct, verdict_table
from common import ARMS, CONDITIONS, JUDGE_MODELS, JUDGES, RESULTS, ROOT, SEED
from harness.metrics import bootstrap_ci

REPEATS = (1, 2)
NOISE_MD = ROOT / "persuasion" / "NOISE.md"


def load(stem: str) -> list[dict]:
    path = RESULTS / f"{stem}.jsonl"
    if not path.exists():
        raise FileNotFoundError(f"{path} missing - run `run.py --condition C0 --repeat K --live` first")
    return [json.loads(line) for line in path.open()]


def verdicts(rows: list[dict]) -> dict[tuple, bool]:
    """(judge, arm, item) -> pass, C0 only, valid verdicts only."""
    vt = verdict_table(r for r in rows if r["condition"] == "C0")
    return {(j, a, i): v["pass"] for (j, a, i, c), v in vt.items() if v["pass"] is not None}


def _ci(vals: list[float], seed: int):
    return bootstrap_ci(vals, n_boot=N_BOOT, seed=seed) if vals else None


def noise_metrics(runs: list[dict[tuple, bool]], hallucinated: dict[str, bool]) -> dict:
    items = sorted(hallucinated)
    out: dict = {}
    for j in JUDGES:
        for a in ARMS:
            changed, any_change, flips = [], [], []
            for i in items:
                vs = [r.get((j, a, i)) for r in runs]
                pairs = [(x, y) for x, y in combinations(vs, 2) if x is not None and y is not None]
                if None not in vs:
                    changed.append(sum(x != y for x, y in pairs) / len(pairs))
                    any_change.append(float(len(set(vs)) > 1))
                if hallucinated[i] and vs[0] is False:
                    flips += [float(v) for v in vs[1:] if v is not None]
            out[f"{j}|{a}"] = {"changed": {"n": len(changed), "ci": _ci(changed, SEED + 10)},
                               "any_change": {"n": len(any_change), "ci": _ci(any_change, SEED + 11)},
                               "noise_flip": {"n": len(flips), "ci": _ci(flips, SEED + 12)}}
    return out


def write_md(m: dict, post1: dict, judges: list[str], repeats: tuple[int, ...], path=NOISE_MD) -> None:
    attacks = [c for c in CONDITIONS if c != "C0"]
    n_runs = len(repeats) + 1
    interim = " **INTERIM: one re-run only.**" if len(repeats) < len(REPEATS) else ""
    L = ["# Noise baseline: verdict changes between runs with no attack", "",
         f"Regenerated by `persuasion/noise.py`.{interim} C0 (clean) only, all 120 items, {n_runs} runs: the original "
         f"post-1 run plus re-run(s) {', '.join(map(str, repeats))} (`run.py --condition C0 --repeat K`). Same "
         "requests, same settings; only the cache key differs.", "",
         f"- **changed**: share of items whose verdict differs between two runs, averaged over the "
         f"{n_runs * (n_runs - 1) // 2} run pair(s).",
         f"- **any change**: share of items whose verdict is not identical in all {n_runs} runs.",
         "- **noise flip**: post 1's flip-rate definition with a clean re-run in place of the attack (wrong "
         "answers that fail in the original C0 run and pass in a re-run, pooled over the re-runs).",
         "- **post-1 flip C1-C4**: the attack flip rates from `RESULTS.md`, same judge and arm.", "",
         "95% bootstrap CIs over items; n = items (or item-runs for noise flip) with valid verdicts in every run "
         "compared.", "",
         "| Judge | Arm | changed | any change | noise flip | " + " | ".join(f"post-1 flip {c}" for c in attacks) + " |",
         "|---|---|---|---|---|" + "---|" * len(attacks)]
    for j in judges:
        for a in ARMS:
            k = f"{j}|{a}"
            p1 = [pct(post1[f"{k}|{c}"]) if f"{k}|{c}" in post1 else "-" for c in attacks]
            L.append(f"| {j} (`{JUDGE_MODELS[j]}`) | {a} | {pct(m[k]['changed'])} | {pct(m[k]['any_change'])} | "
                     f"{pct(m[k]['noise_flip'])} | " + " | ".join(p1) + " |")
    L += ["", "A bootstrap interval of a 0-of-n rate is [0.0, 0.0], which overstates certainty: with 0 events in n "
          "trials the 95% upper bound is about 3/n (rule of three), i.e. about 5-6% at n = 47-59 here.", "",
          "A post-1 flip rate inside the noise-flip interval (or under 3/n when noise flip is 0) for the same judge "
          "and arm is not distinguishable from run-to-run noise at this n.", ""]
    path.write_text("\n".join(L))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repeats", type=int, nargs="+", default=list(REPEATS))
    args = ap.parse_args()
    repeats = tuple(args.repeats)
    sample = {json.loads(l)["response_id"]: json.loads(l) for l in (RESULTS / "sample.jsonl").open()}
    runs = [verdicts(load("judgments"))] + [verdicts(load(f"judgments_repeat{k}")) for k in repeats]
    m = noise_metrics(runs, {i: it["hallucinated"] for i, it in sample.items()})
    post1 = json.loads((RESULTS / "judgments_metrics.json").read_text())["metrics"]["flip"]
    judges = [j for j in JUDGES if any(m[f"{j}|{a}"]["changed"]["n"] for a in ARMS)]
    final = repeats == REPEATS
    out = NOISE_MD if final else RESULTS / "NOISE_interim.md"
    write_md(m, post1, judges, repeats, out)
    (RESULTS / f"noise_metrics{'' if final else '_interim'}.json").write_text(json.dumps(m, indent=1))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
